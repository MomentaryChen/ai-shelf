/**
 * Conversation history: browse, search and resume past AI agent sessions.
 *
 * Pure helpers (no fs / Electron) shared by the main-process scanner, the renderer
 * and tests. Only Claude Code transcripts (`<config>/projects/<encoded-cwd>/<uuid>.jsonl`)
 * are understood today; other tools join by adding a provider in
 * src/electron/conversation-history-providers.ts with their own line parser here.
 *
 * Transcripts are private: callers must never log line contents or JSON parse errors
 * (Node embeds a snippet of the input in `SyntaxError` messages).
 */

export type ConversationProviderId = "claude";

export interface ConversationSummary {
  provider: ConversationProviderId;
  /** Tool id used to launch / resume the session in a pane. */
  tool: string;
  sessionId: string;
  /** Working directory the session ran in (from the records' `cwd`). */
  cwd: string | null;
  /** First real user prompt, flattened to one line. */
  title: string;
  /** First record timestamp (ms since epoch). */
  startedAt: number | null;
  /** File modification time (ms since epoch). */
  updatedAt: number;
  /** User + assistant messages; null until the whole transcript has been read once. */
  messageCount: number | null;
  gitBranch: string | null;
  sizeBytes: number;
  /** Whether `cwd` still exists on disk and matches the transcript's project folder. */
  resumable: boolean;
}

export type ConversationRole = "user" | "assistant";

export interface ConversationMessage {
  role: ConversationRole;
  text: string;
  timestamp: number | null;
}

export interface ConversationDetail {
  summary: ConversationSummary;
  messages: ConversationMessage[];
  /** True when messages were dropped to respect the preview cap. */
  truncated: boolean;
}

export interface ConversationSearchHit {
  summary: ConversationSummary;
  snippet: string;
  role: ConversationRole;
  /** Matching messages in the session (0 when only the title / cwd / branch matched). */
  matchCount: number;
}

export interface ConversationSearchResult {
  hits: ConversationSearchHit[];
  /** True when the result cap was reached before every session was searched. */
  limited: boolean;
  /** True when a newer search superseded this one. */
  cancelled?: boolean;
}

/** One parsed transcript line, reduced to what history needs. */
export type ClaudeLineInfo =
  | {
      kind: "message";
      role: ConversationRole;
      /** Visible text (tool calls, tool results and thinking removed); may be empty. */
      text: string;
      /** True for a prompt the user actually typed (title candidate). */
      isPrompt: boolean;
      timestamp: number | null;
      cwd: string | null;
      gitBranch: string | null;
    }
  | {
      kind: "other";
      timestamp: number | null;
      cwd: string | null;
      gitBranch: string | null;
      /** Title used when the session has no typed prompt (see `FallbackTitleKind`). */
      fallbackTitle?: { kind: FallbackTitleKind; text: string };
    };

/**
 * Titles for sessions without a typed prompt, best first: `/rename` titles, Claude's
 * generated `ai-title`, the slash command that started the session, then old
 * `summary` records.
 */
export type FallbackTitleKind = "custom" | "ai" | "command" | "summary";
const FALLBACK_ORDER: readonly FallbackTitleKind[] = ["custom", "ai", "command", "summary"];

/** `/name args` from a slash-command entry (`<command-name>/x</command-name>…<command-args>…`). */
export function slashCommandTitle(text: string): string | null {
  const name = /<command-name>\s*([^<]*?)\s*<\/command-name>/.exec(text)?.[1];
  if (!name) return null;
  const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim();
  const cmd = name.startsWith("/") ? name : `/${name}`;
  return args ? `${cmd} ${args}` : cmd;
}

/** Prefixes of user-role strings Claude Code injects (slash commands, caveats, hooks). */
const INJECTED_USER_PREFIXES = [
  "<command-name>",
  "<command-message>",
  "<command-args>",
  "<local-command-",
  "<system-reminder>",
  "<user-prompt-submit-hook>",
  "<bash-input>",
  "<bash-stdout>",
  "<bash-stderr>",
  "<task-notification>",
  "Caveat: The messages below were generated by the user while running local commands",
  "[Request interrupted by user",
];

function isInjectedUserText(text: string): boolean {
  const s = text.trimStart();
  return INJECTED_USER_PREFIXES.some((p) => s.startsWith(p));
}

function str(v: unknown): string | null {
  return typeof v === "string" && v.length > 0 ? v : null;
}

function parseTimestamp(v: unknown): number | null {
  if (typeof v !== "string" && typeof v !== "number") return null;
  const ms = typeof v === "number" ? v : Date.parse(v);
  return Number.isFinite(ms) ? ms : null;
}

/** Visible text of a message `content` (string or block array); tool / thinking blocks dropped. */
export function claudeContentText(content: unknown): { text: string; onlyToolResults: boolean } {
  if (typeof content === "string") return { text: content, onlyToolResults: false };
  if (!Array.isArray(content)) return { text: "", onlyToolResults: false };
  const parts: string[] = [];
  let sawToolResult = false;
  let sawOther = false;
  for (const block of content) {
    if (!block || typeof block !== "object") continue;
    const b = block as { type?: unknown; text?: unknown };
    if (b.type === "tool_result") {
      sawToolResult = true;
      continue;
    }
    sawOther = true;
    if (b.type === "text" && typeof b.text === "string") parts.push(b.text);
  }
  return { text: parts.join("\n\n"), onlyToolResults: sawToolResult && !sawOther };
}

/**
 * Cheap pre-filter: Claude Code writes conversation records with `parentUuid` first
 * and bookkeeping records (`api-request`, `file-history-snapshot`, …) with `type`
 * first. Lines this returns false for can be skipped without `JSON.parse`, except
 * for the few bookkeeping types we read.
 */
export function claudeLineMayMatter(line: string): boolean {
  if (!line.startsWith('{"type":')) return true;
  return (
    line.startsWith('{"type":"user"') ||
    line.startsWith('{"type":"assistant"') ||
    line.startsWith('{"type":"summary"') ||
    line.startsWith('{"type":"ai-title"') ||
    line.startsWith('{"type":"custom-title"')
  );
}

/** Parse one Claude Code transcript line. Malformed / unknown lines return null. */
export function parseClaudeLine(line: string): ClaudeLineInfo | null {
  const trimmed = line.trim();
  if (!trimmed.startsWith("{")) return null;
  let rec: unknown;
  try {
    rec = JSON.parse(trimmed);
  } catch {
    return null;
  }
  if (!rec || typeof rec !== "object" || Array.isArray(rec)) return null;
  const r = rec as Record<string, unknown>;
  const timestamp = parseTimestamp(r.timestamp);
  const cwd = str(r.cwd);
  const gitBranch = str(r.gitBranch);
  const type = r.type;

  const fb: [FallbackTitleKind, unknown] | null =
    type === "summary"
      ? ["summary", r.summary]
      : type === "ai-title"
        ? ["ai", r.aiTitle]
        : type === "custom-title"
          ? ["custom", r.customTitle]
          : null;
  if (fb) {
    const text = str(fb[1]);
    return {
      kind: "other",
      timestamp,
      cwd,
      gitBranch,
      ...(text ? { fallbackTitle: { kind: fb[0], text } } : {}),
    };
  }
  if (type !== "user" && type !== "assistant") {
    return { kind: "other", timestamp, cwd, gitBranch };
  }
  // Sub-agent (Task tool) turns are not part of the main conversation.
  if (r.isSidechain === true) return { kind: "other", timestamp, cwd, gitBranch };
  const message = r.message as { role?: unknown; content?: unknown } | undefined;
  if (!message || typeof message !== "object") return { kind: "other", timestamp, cwd, gitBranch };

  const role: ConversationRole = type;
  const { text: raw, onlyToolResults } = claudeContentText(message.content);
  if (onlyToolResults) return { kind: "other", timestamp, cwd, gitBranch };
  if (role === "user" && (r.isMeta === true || isInjectedUserText(raw))) {
    const command = r.isMeta === true ? null : slashCommandTitle(raw);
    return {
      kind: "other",
      timestamp,
      cwd,
      gitBranch,
      ...(command ? { fallbackTitle: { kind: "command" as const, text: command } } : {}),
    };
  }
  const text = raw.trim();
  return {
    kind: "message",
    role,
    text,
    isPrompt: role === "user" && text.length > 0,
    timestamp,
    cwd,
    gitBranch,
  };
}

const TITLE_MAX = 160;

/** One-line title from a prompt: collapse whitespace, cap length. */
export function conversationTitle(text: string, max = TITLE_MAX): string {
  const flat = text.replace(/\s+/g, " ").trim();
  return flat.length > max ? `${flat.slice(0, max - 1).trimEnd()}…` : flat;
}

/**
 * Collects list-row metadata from the head of a transcript. Feed lines in order
 * until `done` — title, cwd, start time and branch are then known.
 */
export class ClaudeHeadCollector {
  title: string | null = null;
  private readonly fallbacks: Partial<Record<FallbackTitleKind, string>> = {};
  startedAt: number | null = null;
  gitBranch: string | null = null;
  /** Distinct cwds seen, in order (Claude may record more than one). */
  readonly cwds: string[] = [];

  get done(): boolean {
    return this.title !== null && this.cwds.length > 0 && this.startedAt !== null;
  }

  /** Best title when no typed prompt was found (empty string when none). */
  get fallbackTitle(): string {
    for (const kind of FALLBACK_ORDER) {
      const text = this.fallbacks[kind];
      if (text) return conversationTitle(text);
    }
    return "";
  }

  add(line: string): void {
    if (!claudeLineMayMatter(line)) return;
    const info = parseClaudeLine(line);
    if (!info) return;
    if (this.startedAt === null && info.timestamp !== null) this.startedAt = info.timestamp;
    if (info.cwd && !this.cwds.includes(info.cwd)) this.cwds.push(info.cwd);
    if (info.gitBranch && !this.gitBranch) this.gitBranch = info.gitBranch;
    if (info.kind === "other" && info.fallbackTitle) {
      const { kind, text } = info.fallbackTitle;
      // ai-title may be rewritten as the session goes on; keep the latest seen.
      if (kind === "ai" || !this.fallbacks[kind]) this.fallbacks[kind] = text;
    }
    if (info.kind === "message" && info.isPrompt && this.title === null) {
      const title = conversationTitle(info.text);
      if (title) this.title = title;
    }
  }
}

export interface ClaudeFullCollectorOptions {
  /** Keep at most this many messages (the rest are counted only). */
  maxMessages?: number;
  /** Cut each kept message to this many characters. */
  maxMessageChars?: number;
}

/** Collects every visible message of a transcript (preview / count). */
export class ClaudeFullCollector {
  readonly messages: ConversationMessage[] = [];
  messageCount = 0;
  lastTimestamp: number | null = null;
  lastGitBranch: string | null = null;
  truncated = false;
  private readonly maxMessages: number;
  private readonly maxChars: number;

  constructor(opts: ClaudeFullCollectorOptions = {}) {
    this.maxMessages = opts.maxMessages ?? Number.POSITIVE_INFINITY;
    this.maxChars = opts.maxMessageChars ?? Number.POSITIVE_INFINITY;
  }

  add(line: string): void {
    if (!claudeLineMayMatter(line)) return;
    const info = parseClaudeLine(line);
    if (!info) return;
    if (info.timestamp !== null) this.lastTimestamp = info.timestamp;
    if (info.gitBranch) this.lastGitBranch = info.gitBranch;
    if (info.kind !== "message" || !info.text) return;
    this.messageCount += 1;
    if (this.messages.length >= this.maxMessages) {
      this.truncated = true;
      return;
    }
    const text =
      info.text.length > this.maxChars ? `${info.text.slice(0, this.maxChars)}…` : info.text;
    if (text.length < info.text.length) this.truncated = true;
    this.messages.push({ role: info.role, text, timestamp: info.timestamp });
  }
}

/** Lower-cased search terms (whitespace separated); empty when the query is blank. */
export function searchTerms(query: string): string[] {
  return query
    .toLowerCase()
    .split(/\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
}

/** True when every term occurs in `text` (case-insensitive). */
export function textMatchesTerms(text: string, terms: readonly string[]): boolean {
  if (terms.length === 0) return false;
  const hay = text.toLowerCase();
  return terms.every((t) => hay.includes(t));
}

/** Short one-line excerpt around the first occurrence of `term`. */
export function searchSnippet(text: string, term: string, radius = 60): string {
  const flat = text.replace(/\s+/g, " ").trim();
  const at = term ? flat.toLowerCase().indexOf(term.toLowerCase()) : -1;
  if (at < 0) return conversationTitle(flat, radius * 2);
  const start = Math.max(0, at - radius);
  const end = Math.min(flat.length, at + term.length + radius);
  return `${start > 0 ? "…" : ""}${flat.slice(start, end).trim()}${end < flat.length ? "…" : ""}`;
}

/** Search state for one transcript: feed lines, then read `matchCount` / `snippet`. */
export class ClaudeSearchCollector {
  matchCount = 0;
  snippet: string | null = null;
  role: ConversationRole = "user";
  /** Terms survive JSON encoding verbatim, so a raw-line check skips most parses. */
  private readonly rawPrefilter: boolean;

  constructor(private readonly terms: readonly string[]) {
    // eslint-disable-next-line no-control-regex
    this.rawPrefilter = terms.every((t) => !/["\\\u0000-\u001f]/.test(t));
  }

  add(line: string): void {
    if (!claudeLineMayMatter(line)) return;
    if (this.rawPrefilter && !textMatchesTerms(line, this.terms)) return;
    const info = parseClaudeLine(line);
    if (!info || info.kind !== "message" || !info.text) return;
    if (!textMatchesTerms(info.text, this.terms)) return;
    this.matchCount += 1;
    if (this.snippet === null) {
      this.snippet = searchSnippet(info.text, this.terms[0] ?? "");
      this.role = info.role;
    }
  }
}

/**
 * Pick the cwd to resume in: the first recorded cwd whose encoded form matches the
 * transcript's project folder (that is where `claude --resume` looks), else the first.
 */
export function pickResumeCwd(
  cwds: readonly string[],
  matchesFolder: (cwd: string) => boolean,
): { cwd: string | null; matchesFolder: boolean } {
  const hit = cwds.find(matchesFolder);
  if (hit) return { cwd: hit, matchesFolder: true };
  return { cwd: cwds[0] ?? null, matchesFolder: false };
}

/** Last path segment of a cwd, for compact project labels. */
export function projectLabel(cwd: string | null): string {
  if (!cwd) return "";
  const parts = cwd.split(/[\\/]/).filter(Boolean);
  return parts[parts.length - 1] ?? cwd;
}

export interface ConversationProjectGroup {
  /** Grouping key (cwd, case-folded on Windows-style paths); "" for unknown. */
  key: string;
  cwd: string | null;
  label: string;
  sessions: ConversationSummary[];
  updatedAt: number;
}

function projectKey(cwd: string | null): string {
  if (!cwd) return "";
  const norm = cwd.replace(/[\\/]+$/, "");
  // Drive-letter paths are case-insensitive (Claude keeps whatever case the process saw).
  return /^[a-zA-Z]:[\\/]/.test(norm) ? norm.toLowerCase().replace(/\//g, "\\") : norm;
}

/** Sessions newest first. */
export function sortByUpdated(sessions: readonly ConversationSummary[]): ConversationSummary[] {
  return [...sessions].sort((a, b) => b.updatedAt - a.updatedAt);
}

/** Group sessions by project cwd; groups and sessions newest first. */
export function groupByProject(
  sessions: readonly ConversationSummary[],
): ConversationProjectGroup[] {
  const map = new Map<string, ConversationProjectGroup>();
  for (const s of sortByUpdated(sessions)) {
    const key = projectKey(s.cwd);
    let g = map.get(key);
    if (!g) {
      g = { key, cwd: s.cwd, label: projectLabel(s.cwd), sessions: [], updatedAt: s.updatedAt };
      map.set(key, g);
    }
    g.sessions.push(s);
  }
  return [...map.values()].sort((a, b) => b.updatedAt - a.updatedAt);
}

/** Sessions belonging to a project group key (see `groupByProject`); all when key is null. */
export function filterByProject(
  sessions: readonly ConversationSummary[],
  key: string | null,
): ConversationSummary[] {
  if (key === null) return [...sessions];
  return sessions.filter((s) => projectKey(s.cwd) === key);
}

