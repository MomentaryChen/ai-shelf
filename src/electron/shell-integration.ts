import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Bump when script bodies change so cached files are rewritten. */
const VERSION = 6;

const BASH_SCRIPT = [
  "# AI Shelf shell integration — OSC 7 (cwd) and OSC 133 (command marks).",
  "# Used as bash --init-file; also safe to source.",
  'if [ -n "${__AISHELF_OSC7_LOADED:-}" ]; then',
  "  return 0 2>/dev/null || true",
  "fi",
  "__AISHELF_OSC7_LOADED=1",
  "",
  'if [ -z "${__AISHELF_BASHRC_DONE:-}" ]; then',
  "  __AISHELF_BASHRC_DONE=1",
  '  if [ -f "$HOME/.bashrc" ]; then',
  "    # shellcheck disable=SC1091",
  '    . "$HOME/.bashrc"',
  "  fi",
  "fi",
  "",
  "__aishelf_emit_osc7() {",
  "  # LC_ALL=C: index PWD as UTF-8 bytes so non-ASCII dirs percent-encode correctly.",
  "  local LC_ALL=C",
  '  local p out="" i=0 c hex',
  "  p=$PWD",
  "  local len=${#p}",
  "  while [ $i -lt $len ]; do",
  "    c=${p:i:1}",
  "    case $c in",
  "      [A-Za-z0-9/._~-]) out+=$c ;;",
  "      *)",
  "        printf -v hex '%%%02X' \"'$c\"",
  "        out+=$hex",
  "        ;;",
  "    esac",
  "    i=$((i + 1))",
  "  done",
  '  printf \'\\033]7;file://%s%s\\007\' "${HOSTNAME:-}" "$out"',
  "}",
  "",
  "# OSC 133 command marks: A prompt start, B input start, C output start, D;<exit> done.",
  "# A/B live in PS1, C in PS0 (bash >= 4.4), D in the first PROMPT_COMMAND entry.",
  "__aishelf_cmd_ran=0",
  "__aishelf_has_ps0=0",
  'if [ "${BASH_VERSINFO[0]:-0}" -gt 4 ] || { [ "${BASH_VERSINFO[0]:-0}" -eq 4 ] && [ "${BASH_VERSINFO[1]:-0}" -ge 4 ]; }; then',
  "  __aishelf_has_ps0=1",
  "fi",
  "__aishelf_mark_a=$'\\\\[\\033]133;A\\007\\\\]'",
  "__aishelf_mark_b=$'\\\\[\\033]133;B\\007\\\\]'",
  "",
  "# First PROMPT_COMMAND entry: sees the command's real $? and hands it on unchanged.",
  "__aishelf_precmd() {",
  "  local __aishelf_status=$?",
  '  if [ "${__aishelf_cmd_ran:-0}" = 1 ]; then',
  "    printf '\\033]133;D;%s\\007' \"$__aishelf_status\"",
  "  fi",
  "  # Without PS0 every prompt after the first closes a command (empty Enter included).",
  '  if [ "$__aishelf_has_ps0" = 1 ]; then __aishelf_cmd_ran=0; else __aishelf_cmd_ran=1; fi',
  "  __aishelf_emit_osc7",
  "  return $__aishelf_status",
  "}",
  "",
  "# Last PROMPT_COMMAND entry: re-wrap PS1 when a theme rebuilt it.",
  "__aishelf_wrap_ps1() {",
  "  local __aishelf_status=$?",
  "  case ${PS1:-} in",
  '    *"$__aishelf_mark_b"*) ;;',
  '    *) PS1="$__aishelf_mark_a${PS1:-}$__aishelf_mark_b" ;;',
  "  esac",
  "  return $__aishelf_status",
  "}",
  "",
  'if [ "$__aishelf_has_ps0" = 1 ]; then',
  "  # The arithmetic subscript sets the flag in this shell; the expansion itself is empty.",
  "  case ${PS0:-} in",
  '    *"133;C"*) ;;',
  "    *) PS0=\"${PS0:-}\"'${__aishelf_ps0_sink[__aishelf_cmd_ran=1]:-}'$'\\033]133;C\\007' ;;",
  "  esac",
  "fi",
  "",
  "if declare -p PROMPT_COMMAND 2>/dev/null | grep -q 'declare -a'; then",
  '  case " ${PROMPT_COMMAND[*]} " in',
  '    *" __aishelf_precmd "*) ;;',
  '    *) PROMPT_COMMAND=(__aishelf_precmd "${PROMPT_COMMAND[@]}" __aishelf_wrap_ps1) ;;',
  "  esac",
  "else",
  // Quote the `;` inside the pattern — bare `;` is a case-clause separator and
  // makes bash reject the script with "syntax error near unexpected token `;`".
  // Append with a newline: a user string ending in `;` would turn `;;` into a syntax error.
  '  case ";${PROMPT_COMMAND:-};" in',
  '    *";__aishelf_precmd;"*) ;;',
  '    *) PROMPT_COMMAND="__aishelf_precmd;${PROMPT_COMMAND:-}"$\'\\n\'"__aishelf_wrap_ps1" ;;',
  "  esac",
  "fi",
  "",
  "__aishelf_emit_osc7",
  "",
].join("\n");

const PWSH_SCRIPT = [
  "# AI Shelf shell integration — OSC 7 (cwd) and OSC 133 (command marks).",
  "if (Get-Variable -Name __AIShelfOsc7Loaded -Scope Global -ErrorAction SilentlyContinue) {",
  "  return",
  "}",
  "$Global:__AIShelfOsc7Loaded = $true",
  "",
  "function Global:__AIShelf-Emit-Osc7 {",
  "  try {",
  "    $providerPath = $PWD.ProviderPath",
  "    if (-not $providerPath) { return }",
  "    $normalized = $providerPath.Replace('\\', '/')",
  "    $sb = New-Object System.Text.StringBuilder",
  "    foreach ($ch in $normalized.ToCharArray()) {",
  "      $code = [int][char]$ch",
  "      if (",
  "        ($code -ge 48 -and $code -le 57) -or",
  "        ($code -ge 65 -and $code -le 90) -or",
  "        ($code -ge 97 -and $code -le 122) -or",
  "        $ch -eq '/' -or $ch -eq ':' -or $ch -eq '-' -or $ch -eq '_' -or $ch -eq '.' -or $ch -eq '~'",
  "      ) {",
  "        [void]$sb.Append($ch)",
  "      } else {",
  "        foreach ($b in [System.Text.Encoding]::UTF8.GetBytes([string]$ch)) {",
  "          [void]$sb.AppendFormat('%{0:X2}', $b)",
  "        }",
  "      }",
  "    }",
  "    $pathEnc = $sb.ToString()",
  "    if ($pathEnc -match '^[A-Za-z]:') {",
  '      $uri = "file:///$pathEnc"',
  "    } else {",
  '      $uri = "file://$pathEnc"',
  "    }",
  "    $esc = [char]27",
  "    $bel = [char]7",
  '    [Console]::Write("$esc]7;$uri$bel")',
  "  } catch {",
  "    # never break the prompt",
  "  }",
  "}",
  "",
  "if (Test-Path Function:\\prompt) {",
  "  $Global:__AIShelfOriginalPrompt = $function:prompt",
  "}",
  "",
  "# OSC 133 command marks (same scheme as VS Code / Windows Terminal shell integration):",
  "# D;<exit> + A before the prompt, B after it, C once PSReadLine accepts a line.",
  "$Global:__AIShelfLastHistoryId = -1",
  "$Global:__AIShelfCmdStarted = $false",
  "$Global:__AIShelfReadLineHooked = $false",
  "",
  "# Wrap PSConsoleHostReadLine (not the Enter key) so any accept binding works and",
  "# the user's own key handlers stay untouched. Retried each prompt until PSReadLine is loaded.",
  "function Global:__AIShelf-Hook-ReadLine {",
  "  if ($Global:__AIShelfReadLineHooked) { return }",
  "  try {",
  "    if (-not (Get-Module -Name PSReadLine)) { return }",
  "    if (-not (Test-Path Function:\\PSConsoleHostReadLine)) { return }",
  "    $Global:__AIShelfOriginalReadLine = $function:PSConsoleHostReadLine",
  "    $Global:__AIShelfReadLineHooked = $true",
  "    function Global:PSConsoleHostReadLine {",
  "      $line = & $Global:__AIShelfOriginalReadLine",
  "      try {",
  "        if (-not [string]::IsNullOrWhiteSpace([string]$line)) {",
  "          $Global:__AIShelfCmdStarted = $true",
  '          [Console]::Write("$([char]27)]133;C$([char]7)")',
  "        }",
  "      } catch {",
  "        # never break input",
  "      }",
  "      $line",
  "    }",
  "  } catch {",
  "    # leave PSReadLine alone",
  "  }",
  "}",
  "",
  "function Global:prompt {",
  "  # Capture before anything else runs: $? and $LASTEXITCODE describe the user's command.",
  "  $aishelfOk = $global:?",
  "  $aishelfNativeCode = $global:LASTEXITCODE",
  "  $aishelfMarks = ''",
  "  try {",
  "    $esc = [char]27",
  "    $bel = [char]7",
  "    $hist = Get-History -Count 1",
  "    $histId = 0",
  "    if ($null -ne $hist) { $histId = $hist.Id }",
  "    if ($Global:__AIShelfLastHistoryId -ne -1 -and $histId -ne $Global:__AIShelfLastHistoryId) {",
  "      $code = 0",
  "      if (-not $aishelfOk) {",
  "        $code = 1",
  "        if ($aishelfNativeCode -is [int] -and $aishelfNativeCode -ne 0) { $code = $aishelfNativeCode }",
  "      }",
  '      [Console]::Write("$esc]133;D;$code$bel")',
  "    } elseif ($Global:__AIShelfCmdStarted) {",
  '      [Console]::Write("$esc]133;D$bel")',
  "    }",
  "    $Global:__AIShelfCmdStarted = $false",
  "    $Global:__AIShelfLastHistoryId = $histId",
  "    __AIShelf-Emit-Osc7",
  '    [Console]::Write("$esc]133;A$bel")',
  '    $aishelfMarks = "$esc]133;B$bel"',
  "    __AIShelf-Hook-ReadLine",
  "  } catch {",
  "    # never break the prompt",
  "  }",
  "  $global:LASTEXITCODE = $aishelfNativeCode",
  "  # Hand $? back to themes that read it (oh-my-posh, starship).",
  "  if (-not $aishelfOk) { Write-Error 'aishelf' -ErrorAction Ignore }",
  "  if ($null -ne $Global:__AIShelfOriginalPrompt) {",
  "    $text = (& $Global:__AIShelfOriginalPrompt) -join ''",
  "  } else {",
  "    $text = \"PS $($executionContext.SessionState.Path.CurrentLocation)$('>' * ($nestedPromptLevel + 1)) \"",
  "  }",
  "  return $text + $aishelfMarks",
  "}",
  "",
  "__AIShelf-Emit-Osc7",
  "",
].join("\n");

export interface ShellIntegrationPaths {
  bash: string;
  pwsh: string;
}

let cached: { baseDir: string; paths: ShellIntegrationPaths } | null = null;

/** Write versioned integration scripts under userData (cached per process). */
export function ensureShellIntegrationScripts(baseDir: string): ShellIntegrationPaths {
  if (cached?.baseDir === baseDir) return cached.paths;
  const dir = join(baseDir, "shell-integration");
  mkdirSync(dir, { recursive: true });
  const bash = join(dir, `osc7.v${VERSION}.sh`);
  const pwsh = join(dir, `osc7.v${VERSION}.ps1`);
  writeFileSync(bash, BASH_SCRIPT, "utf8");
  writeFileSync(pwsh, PWSH_SCRIPT, "utf8");
  cached = { baseDir, paths: { bash, pwsh } };
  return cached.paths;
}

export function psSingleQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}
